export function chaptersFor(id) {
  const chapters = curricula[id];
  if (!chapters) throw Error(`Missing curriculum ${id}`);
  return chapters;
}
export const chapterById = (topic, id) =>
  chaptersFor(topic).find((c) => c.id === id) || null;
export function resolveChapter(
  topic,
  record = {},
  level = "L2",
  explicit = "",
) {
  const chapters = chaptersFor(topic);
  if (chapterById(topic, explicit)) return explicit;
  if (level === "L3")
    return (chapters.find((c) => c.code) || chapters.at(-1)).id;
  if (level === "L4")
    return (chapters.find((c) => c.quiz) || chapters.at(-1)).id;
  return chapterById(topic, record.mechanismReading?.last)
    ? record.mechanismReading.last
    : chapters[0].id;
}
