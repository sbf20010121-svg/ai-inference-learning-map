export function chapterArcFor(courseId, chapterId) {
  return chapterArcs[courseId + "/" + chapterId] || null;
}

export function validateChapterArcs() {
  for (const [key, arc] of Object.entries(chapterArcs)) {
    const [courseId, chapterId] = key.split("/");
    if (!chaptersFor(courseId).some((chapter) => chapter.id === chapterId))
      throw new Error("Unknown chapter arc: " + key);
    for (const field of ["opening", "takeaway", "bridge"])
      if (typeof arc[field] !== "string" || !arc[field].trim())
        throw new Error("Missing " + field + " in chapter arc: " + key);
    if (!Array.isArray(arc.terms) || arc.terms.length === 0)
      throw new Error("Missing first-use terms in chapter arc: " + key);
    for (const term of arc.terms)
      if (!Array.isArray(term) || term.length !== 2 || !term.every((x) => typeof x === "string" && x.trim()))
        throw new Error("Malformed term definition in chapter arc: " + key);
  }
  return true;
}

validateChapterArcs();
